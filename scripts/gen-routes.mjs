// Generates src/client/registry.ts from the route modules in src/client/routes (runs before dev/build/typecheck).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve("src/client/routes");
const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name === "route.ts") files.push(p);
  }
})(root);

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const rows = files.map((f) => {
  const rel = path.relative(root, path.dirname(f)).split(path.sep).filter(Boolean);
  const keys = [];
  const body = rel
    .map((seg) => {
      const m = /^\[(.+)\]$/.exec(seg);
      if (m) {
        keys.push(m[1]);
        return "/([^/]+)";
      }
      return "/" + escapeRe(seg);
    })
    .join("");
  return { source: "^/api" + body + "/?$", keys, mod: "./routes/" + rel.join("/") + "/route", dynamic: keys.length };
});
// static routes first, then dynamic ones
rows.sort((a, b) => a.dynamic - b.dynamic || b.source.length - a.source.length);

const out = `// AUTO-GENERATED by scripts/gen-routes.mjs — do not edit.
export interface RouteEntry {
  pattern: RegExp;
  keys: string[];
  load: () => Promise<Record<string, unknown>>;
}
export const REGISTRY: RouteEntry[] = [
${rows.map((r) => `  { pattern: new RegExp(${JSON.stringify(r.source)}), keys: ${JSON.stringify(r.keys)}, load: () => import(${JSON.stringify(r.mod)}) },`).join("\n")}
];
`;
fs.writeFileSync("src/client/registry.ts", out);
console.log(`registry: ${rows.length} routes`);
